import {assertTestEnvironment} from "./test-environment";
assertTestEnvironment();
import {chromium,devices} from "playwright";
import AxeBuilder from "@axe-core/playwright";
import {db} from "../src/lib/db";
import {randomBytes} from "node:crypto";
import assert from "node:assert/strict";
const result=await db.query('SELECT u.email FROM "user" u JOIN app_admin a ON a.user_id=u.id WHERE u.name=$1 LIMIT 1',["Admin"]);
assert.ok(result.rowCount,"test administrator exists");
await db.query('INSERT INTO onboarding_state(user_id,completed,step) SELECT id,true,\'review\' FROM "user" WHERE email=$1 ON CONFLICT(user_id) DO UPDATE SET completed=true',[result.rows[0].email]);
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]}),context=await browser.newContext({viewport:{width:1366,height:950}});
const page=await context.newPage(),failures:string[]=[];
page.on("pageerror",e=>failures.push(e.message));
await page.goto("http://localhost:3000");
await page.getByLabel("E-post",{exact:true}).fill(result.rows[0].email);
await page.getByLabel("Passord",{exact:true}).fill("admin-test-password-only-!42");
await page.getByRole("button",{name:"Logg inn",exact:true}).click();
await page.getByRole("navigation",{name:"Hovedmeny"}).getByRole("button",{name:"Administrasjon",exact:true}).click();
await page.getByRole("heading",{name:"Inviter en venn",exact:true}).waitFor();
const email="ui-invite-"+randomBytes(4).toString("hex")+"@example.test";
await page.getByLabel("Vennens e-postadresse",{exact:true}).fill(email);
await page.getByRole("button",{name:"Lag invitasjon",exact:true}).click();
const field=page.getByLabel("Invitasjonslenke",{exact:true});
await field.waitFor();assert.ok((await field.inputValue()).includes("invite="));
const row=page.locator(".admin-user-row").filter({hasText:email});
await row.getByRole("button",{name:"Trekk tilbake",exact:true}).click();
await row.waitFor({state:"detached"});
console.log("PASS: desktop admin navigation, invitation creation and revoke through UI");
let axe=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze();
assert.deepEqual(axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})),[]);
const mobile=await browser.newContext({...devices["iPhone 13"],storageState:await context.storageState()}),phone=await mobile.newPage();
await phone.goto("http://localhost:3000");
await phone.getByRole("navigation",{name:"Mobilmeny"}).getByRole("button",{name:"Mer",exact:true}).click();
await phone.locator(".mobile-menu").getByRole("menuitem",{name:"Administrasjon",exact:true}).click();
await phone.getByRole("heading",{name:"Inviter en venn",exact:true}).waitFor();
assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
axe=await new AxeBuilder({page:phone}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze();
assert.deepEqual(axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})),[]);
assert.deepEqual(failures,[]);
console.log("PASS: iPhone admin navigation, no horizontal overflow, zero desktop/mobile axe violations and no JS errors");
await browser.close();await db.end();
